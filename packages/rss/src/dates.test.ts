import { describe, expect, it } from 'vitest'
import { parseDate } from './dates'

describe('RFC 822 dates', () => {
  it.each([
    ['Fri, 21 Jul 2023 09:04 EDT', '2023-07-21T13:04:00.000Z'],
    ['Tue, 01 Aug 2023 23:25:57 -0400', '2023-08-02T03:25:57.000Z'],
    ['Tue, 10 Jun 2003 04:00:00 GMT', '2003-06-10T04:00:00.000Z'],
    ['Sat, 12 Sep 2026 00:00:00 -0400', '2026-09-12T04:00:00.000Z'],
    ['20 May 03 08:56:02 UT', '2003-05-20T08:56:02.000Z'],
    ['1 Jan 99 00:00 PST', '1999-01-01T08:00:00.000Z'],
    ['12 September 2026 10:00 Z', '2026-09-12T10:00:00.000Z'],
    ['Mon 26 Jun 2023 12:45', '2023-06-26T12:45:00.000Z'],
    ['Mon, 26 Jun 2023 12:45 CEST', '2023-06-26T12:45:00.000Z'],
    ['Thu, 01 Jan 2026 12:00:00 EST', '2026-01-01T17:00:00.000Z'],
    ['Thu, 01 Jan 2026 12:00:00 CST', '2026-01-01T18:00:00.000Z'],
    ['Thu, 01 Jan 2026 12:00:00 CDT', '2026-01-01T17:00:00.000Z'],
    ['Thu, 01 Jan 2026 12:00:00 MST', '2026-01-01T19:00:00.000Z'],
    ['Thu, 01 Jan 2026 12:00:00 MDT', '2026-01-01T18:00:00.000Z'],
    ['Thu, 01 Jan 2026 12:00:00 PDT', '2026-01-01T19:00:00.000Z'],
    ['Thu, 01 Jan 2026 12:00:00 +05:30', '2026-01-01T06:30:00.000Z'],
    ['Thu, 01 Jan 2026 12:00:00 A', '2026-01-01T13:00:00.000Z'],
    ['Thu, 01 Jan 2026 12:00:00 K', '2026-01-01T22:00:00.000Z'],
    ['Thu, 01 Jan 2026 12:00:00 M', '2026-01-02T00:00:00.000Z'],
    ['Thu, 01 Jan 2026 12:00:00 N', '2026-01-01T11:00:00.000Z'],
    ['Thu, 01 Jan 2026 12:00:00 Y', '2026-01-01T00:00:00.000Z']
  ])('reads %s', (value, iso) => {
    expect(parseDate(value)).toBe(iso)
  })
})

describe('RFC 3339 and W3CDTF dates', () => {
  it.each([
    ['2023-07-22T10:30:00Z', '2023-07-22T10:30:00.000Z'],
    ['2000-01-01T12:00+00:00', '2000-01-01T12:00:00.000Z'],
    ['2000-08-09T09:30-05:00', '2000-08-09T14:30:00.000Z'],
    ['2020-08-07T11:44:36-05:00', '2020-08-07T16:44:36.000Z'],
    ['2026-09-12t08:00:00.250z', '2026-09-12T08:00:00.250Z'],
    ['2026-09-12 08:00:00.123456+0200', '2026-09-12T06:00:00.123Z'],
    ['2026-09-12T08:00:00', '2026-09-12T08:00:00.000Z'],
    ['2026-09-12', '2026-09-12T00:00:00.000Z']
  ])('reads %s', (value, iso) => {
    expect(parseDate(value)).toBe(iso)
  })
})

describe('what is not a date', () => {
  it.each(['', '   ', 'not a date', '2026-02-30', '31 Feb 2026 10:00 GMT', '2026-13-01', 'Fri, 21 Foo 2023 09:04 EDT', '2026-09-12T25:00:00Z'])(
    'reads %j as empty',
    (value) => {
      expect(parseDate(value)).toBe('')
    }
  )

  it('reads a missing value as empty', () => {
    expect(parseDate(undefined)).toBe('')
  })
})
